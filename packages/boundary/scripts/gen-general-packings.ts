/**
 * Test packings of balls on the five containers beyond the tesseract (no records: BOUNDARY.md section 4A.7). For each container and
 * a few P: a random sequential layout (balls added at random points while they conflict with none, at an edge raised by 6% after a
 * failed round), then the kernel's finish(), which draws the edge in until the balls touch (valid at tol 0). Written raw to
 * python/boundary/fixtures/general_packings_raw.json; python/boundary/build_general_packings.py scales each to strict validity and
 * certifies it exactly, giving general_packings.json.
 *
 *   npx tsx packages/boundary/scripts/gen-general-packings.ts
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ballBounds, boundaryKernel, getPolytope } from "../src/index";
import { ChainMetric } from "../src/search/balls";
import { randomCellPoint } from "../src/search/chart";
import { mulberry32, randInt } from "../src/search/random";
import type { PolytopeName } from "../src/index";

const out = fileURLToPath(new URL("../../../python/boundary/fixtures/general_packings_raw.json", import.meta.url));
const PLAN: [PolytopeName, number[]][] = [
  ["5cell", [1, 2, 3, 5, 8, 12]],
  ["16cell", [1, 2, 4, 6, 10, 16]],
  ["24cell", [1, 2, 3, 6, 12, 24]],
  ["600cell", [1, 2, 3, 5]],
  ["120cell", [1, 2, 3]],
];
const rand = mulberry32(777);
const packings: Record<string, unknown>[] = [];
for (const [name, Ps] of PLAN) {
  const poly = getPolytope(name);
  const metric = new ChainMetric(poly);
  const bound = ballBounds(name, 1).onePiece;
  for (const P of Ps) {
    const kernel = boundaryKernel({ polytope: name, piece: "ball", P });
    const t0 = performance.now();
    let s = bound * (P === 1 ? 1.05 : 1.2);
    const cells = new Int32Array(P);
    const U = new Float64Array(3 * P);
    let ok = false;
    for (let round = 0; round < 40 && !ok; round++, s *= 1.06) {
      let placed = 0;
      for (let tries = 0; placed < P && tries < 300 * P; tries++) {
        cells[placed] = randInt(rand, poly.cells.length);
        U.set(randomCellPoint(poly, cells[placed], s, rand, 0.7), 3 * placed);
        const sub = Float64Array.from(U.subarray(0, 3 * placed + 3), (x) => x * 2);
        if (metric.evaluate(cells.subarray(0, placed + 1), sub, s * 2, null, true, { focus: placed }) <= 0) placed++;
      }
      ok = placed === P;
    }
    if (!ok) throw new Error(`no layout for ${name} ${P}`);
    const config = {
      s,
      pieces: Array.from({ length: P }, (_, i) => ({ cell: cells[i], u: [U[3 * i], U[3 * i + 1], U[3 * i + 2]] })),
    };
    const st = kernel.fromConfig(config);
    const fin = st && kernel.finish(st);
    if (!fin) throw new Error(`finish failed for ${name} ${P}`);
    const v = kernel.validate(fin.config);
    if (!v.valid) throw new Error(`invalid after finish: ${name} ${P} ${v.reasons[0]}`);
    packings.push({
      id: `boundary/${name}/ball/${P}`,
      polytope: name,
      P,
      source: "random sequential layout, finish()",
      config: fin.config,
      ts_score: fin.score,
    });
    console.log(
      name,
      P,
      "s",
      fin.score.toFixed(6),
      "bound",
      ballBounds(name, P).value.toFixed(6),
      `${((performance.now() - t0) / 1000).toFixed(1)}s`,
    );
  }
}
writeFileSync(
  out,
  JSON.stringify({ note: "generated by packages/boundary/scripts/gen-general-packings.ts (seed 777)", packings }),
);
console.log("wrote", packings.length);
