/**
 * Test packings of Platonic solids on the regular 4-polytopes (no records: BOUNDARY.md section 4C.6). Two kinds:
 *  - the cells themselves at s = 1, each solid centred in the cell of its own shape and turned onto it (exact: the 5 tetrahedra of the
 *    5-cell, the 16 of the 16-cell, the 24 octahedra of the 24-cell, and subsets of 24 cells of the 120-cell and the 600-cell);
 *  - a few short seeded runs of the boundary search, to show that it works on every container (touching: valid at tolerance 0).
 * Written raw to python/boundary/fixtures/platonic_packings_raw.json; python/boundary/build_platonic_packings.py scales each to strict
 * validity and certifies it exactly, giving platonic_packings.json.
 *
 *   npx tsx packages/boundary/scripts/gen-platonic-packings.ts [cells|search|all]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { BoundaryConfig, PolytopeName, PolytopePieceName } from "../src/index";
import { getPolytope, matrixToQuaternion, pieceBounds, pieceShape, rotationOnto, searchBoundary, validateBoundary } from "../src/index";

const out = fileURLToPath(new URL("../../../python/boundary/fixtures/platonic_packings_raw.json", import.meta.url));
const which = process.argv[2] ?? "all";

interface Raw {
  id: string;
  polytope: PolytopeName;
  piece: PolytopePieceName;
  P: number;
  source: string;
  config: BoundaryConfig;
}
const packings: Raw[] = existsSync(out) ? JSON.parse(readFileSync(out, "utf8")).packings : [];
const save = () =>
  writeFileSync(out, JSON.stringify({ note: "generated by packages/boundary/scripts/gen-platonic-packings.ts", packings }));
const put = (r: Raw) => {
  const i = packings.findIndex((p) => p.id === r.id && p.source === r.source);
  if (i >= 0) packings[i] = r;
  else packings.push(r);
  save();
};

if (which === "cells" || which === "all") {
  const PLAN: [PolytopeName, PolytopePieceName, number][] = [
    ["5cell", "tetrahedron", 5],
    ["16cell", "tetrahedron", 16],
    ["24cell", "octahedron", 24],
    ["120cell", "dodecahedron", 24],
    ["600cell", "tetrahedron", 24],
  ];
  for (const [name, piece, P] of PLAN) {
    const poly = getPolytope(name);
    const sh = pieceShape(piece);
    // the first P cells: for the 120-cell and the 600-cell a subset of the tiling (touching solids in 24 of the cells)
    const config: BoundaryConfig = {
      s: 1,
      pieces: poly.cells.slice(0, P).map((c) => ({ cell: c.index, u: [0, 0, 0], q: matrixToQuaternion(rotationOnto(sh, c.vertices as [number, number, number][])!) })),
    };
    const v = validateBoundary({ polytope: name, piece, P }, config, { tol: 1e-9 });
    if (!v.ok) throw new Error(`cells of the ${name}: ${v.reasons[0]}`);
    put({ id: `boundary/${name}/${piece}/${P}`, polytope: name, piece, P, source: P === poly.cells.length ? "the cells themselves, s = 1" : `${P} of the ${poly.cells.length} cells, s = 1`, config });
    console.log("cells", name, piece, P, "s = 1");
  }
}

if (which === "search" || which === "all") {
  // [container, solid, P, evaluations, seed]
  const PLAN: [PolytopeName, PolytopePieceName, number, number, number][] = [
    ["tesseract", "icosahedron", 2, 40000, 1],
    ["tesseract", "tetrahedron", 3, 90000, 2],
    ["5cell", "octahedron", 2, 60000, 3],
    ["16cell", "cube", 2, 60000, 4],
    ["24cell", "tetrahedron", 3, 60000, 5],
    ["120cell", "dodecahedron", 2, 40000, 6],
    ["600cell", "octahedron", 2, 60000, 7],
  ];
  for (const [name, piece, P, evals, seed] of PLAN) {
    const t0 = performance.now();
    const r = searchBoundary({ polytope: name, piece, P }, { seed, budget: { evals } });
    const secs = ((performance.now() - t0) / 1000).toFixed(0);
    if (!r.config || r.score === null) {
      console.log("search", name, piece, P, "found nothing in", evals, "evaluations,", secs, "s");
      continue;
    }
    const v = validateBoundary({ polytope: name, piece, P }, r.config, { tol: 0 });
    if (!v.ok) throw new Error(`search result invalid: ${name} ${piece} ${P} ${v.reasons[0]}`);
    put({ id: `boundary/${name}/${piece}/${P}`, polytope: name, piece, P, source: `boundary search, seed ${seed}, ${evals} evaluations`, config: r.config });
    console.log("search", name, piece, P, "s", r.score.toFixed(6), "bound", pieceBounds(name, piece, P).value.toFixed(6), `${secs}s`);
  }
}
