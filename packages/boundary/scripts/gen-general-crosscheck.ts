/**
 * The engine's verdicts and chain distances on balls on the five containers beyond the tesseract (and on the tesseract),
 * for the general exact certifier's cross-check (python/boundary/test_general.py). Seeded random configurations of one to
 * three balls: the first at a random point of a random cell, the second at the end of a geodesic from it (so that many pairs
 * interact across ridges), sometimes a third at random; kept while the class (valid or invalid at tol 1e-9) is under its quota.
 * For each case: validateBoundary at tol 1e-9 and tol 0; the geodesic distance of every pair and the shortest loop at every
 * centre (chains, reach 1.2 in site units), and every centre's clearance (reach 0.75).
 *
 * Usage: npx tsx packages/boundary/scripts/gen-general-crosscheck.ts [out.json]
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { BoundaryConfig, PolytopeName } from "../src/index";
import {
  ballBounds,
  clampToCell,
  enumerateChains,
  geodesicDistance,
  geodesicLoop,
  getPolytope,
  hingeClearance,
  traceGeodesic,
  validateBoundary,
} from "../src/index";
import { randomCellPoint } from "../src/search/chart";

const root = (p: string) => fileURLToPath(new URL(`../../../${p}`, import.meta.url));
const out = process.argv[2] ?? root("python/boundary/fixtures/general_crosscheck.json");

function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const finite = (x: number) => (Number.isFinite(x) ? x : null);
const rand = mulberry32(20261101);
const direction = () => {
  for (;;) {
    const v = [2 * rand() - 1, 2 * rand() - 1, 2 * rand() - 1];
    const n = Math.hypot(v[0], v[1], v[2]);
    if (n > 0.1 && n <= 1) return v.map((x) => x / n);
  }
};

// quota per container: valid and invalid cases (the two big containers are slow for the exact side)
const PLAN: [PolytopeName, number][] = [
  ["5cell", 20],
  ["16cell", 20],
  ["24cell", 20],
  ["tesseract", 10],
  ["600cell", 6],
  ["120cell", 4],
];
const cases: Record<string, unknown>[] = [];
for (const [name, quota] of PLAN) {
  const poly = getPolytope(name);
  const bound = ballBounds(name, 1).onePiece;
  const q = { valid: 0, invalid: 0 };
  for (let t = 0; (q.valid < quota || q.invalid < quota) && t < 4000; t++) {
    const s = bound * (1.0 + 0.9 * rand());
    const c0 = Math.floor(rand() * poly.cells.length);
    const u0 = randomCellPoint(poly, c0, s, rand, 0.7);
    const pieces: { cell: number; u: number[] }[] = [{ cell: c0, u: u0 }];
    const walk = traceGeodesic(poly, s, c0, u0, direction(), 0.5 + 1.0 * rand());
    if (walk.hitHinge) continue;
    pieces.push({ cell: walk.cell, u: walk.u });
    if (rand() < 0.3) {
      const c2 = Math.floor(rand() * poly.cells.length);
      pieces.push({ cell: c2, u: randomCellPoint(poly, c2, s, rand, 0.7) });
    }
    const config: BoundaryConfig = { s, pieces };
    const problem = { polytope: name, piece: "ball" as const, P: pieces.length };
    const v9 = validateBoundary(problem, config, { tol: 1e-9 });
    const k = v9.ok ? "valid" : "invalid";
    if (q[k] >= quota) continue;
    q[k]++;
    const v0 = validateBoundary(problem, config, { tol: 0 });
    const pairs: [number, number, number | null][] = [];
    for (let i = 0; i < pieces.length; i++)
      for (let j = i + 1; j < pieces.length; j++)
        pairs.push([i, j, finite(geodesicDistance(poly, s, pieces[i], pieces[j], 1.2))]);
    cases.push({
      id: `${name}:random:${t}`,
      polytope: name,
      P: pieces.length,
      config,
      ts_valid_1e9: v9.ok,
      ts_valid_0: v0.ok,
      ts_reason: [...v9.reasons, ...v0.reasons][0] ?? null,
      pairs,
      loops: pieces.map((p, i) => [i, finite(geodesicLoop(poly, s, p, 1.2))]),
      clearance: pieces.map((p) => finite(hingeClearance(poly, s, p, 0.75))),
      // chains of each ball at reach 1 (the diameter): the float enumerator's node count, to compare with the exact one's
      chains: pieces.map(
        (p) => enumerateChains(poly, s, p.cell, clampToCell(poly, p.cell, p.u, s), 1, { maxChains: 100000 }).length,
      ),
    });
  }
  console.log(name, q);
}
writeFileSync(
  out,
  JSON.stringify({
    note: "generated by packages/boundary/scripts/gen-general-crosscheck.ts (random seed 20261101); engine verdicts at tol 1e-9 and 0, chain distances (reach 1.2, clearance 0.75, site units)",
    cases,
  }),
);
console.log(`wrote ${cases.length} cases`);
