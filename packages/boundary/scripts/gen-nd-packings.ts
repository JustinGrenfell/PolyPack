/**
 * Test packings of balls on the simplex, orthoplex and demicube (d = 5..10; no records: BOUNDARY.md 4C.7). For each of the 18 containers:
 *  - P = 1: one ball at the centre of a cell, at the edge from which it is valid (ndCentreEdge);
 *  - the exact layout (P balls at cell centres, valid from the derived edge ndPairEdge): P = d + 1 on the simplex, 2 on the orthoplex,
 *    2 d on the demicube;
 *  - two short seeded runs of the boundary search (seeds finished by the kernel, no optimiser): P = 4 and P = 24.
 * Written raw to python/boundary/fixtures/nd_packings_raw.json; python/boundary/build_nd_packings.py scales each to strict validity and
 * certifies it exactly, giving nd_packings.json.
 *
 *   npx tsx packages/boundary/scripts/gen-nd-packings.ts
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ND_NAMES, boundaryKernel, getND, ndBound, ndCentreEdge, ndPairEdge, ndParse, searchBoundary, validateBoundary } from "../src/index";
import { mulberry32 } from "../src/search/random";

const out = fileURLToPath(new URL("../../../python/boundary/fixtures/nd_packings_raw.json", import.meta.url));
const packings: Record<string, unknown>[] = [];
const rand = mulberry32(2026);
void rand;

for (const name of ND_NAMES) {
  const p = ndParse(name)!;
  const C = getND(name);
  const add = (P: number, source: string, config: { s: number; pieces: unknown[] }) => {
    const v = validateBoundary({ polytope: name, piece: "ball", P }, config, { tol: 0 });
    if (!v.ok) throw new Error(`${name} ${P} ${source}: ${v.reasons[0]}`);
    packings.push({ id: `boundary/${name}/ball/${P}`, polytope: name, P, source, config, ts_score: config.s, bound: ndBound(p.family, p.d, P) });
    console.log(name, P, source, "s", config.s.toFixed(6), "bound", ndBound(p.family, p.d, P).toFixed(6));
  };
  // P = 1
  add(1, "one ball at a cell centre", { s: ndCentreEdge(name) * (1 + 1e-9), pieces: [{ cell: 0, u: new Array(C.n).fill(0) }] });
  // the exact layout
  const Pex = p.family === "simplex" ? p.d + 1 : p.family === "orthoplex" ? 2 : 2 * p.d;
  const cells = p.family === "orthoplex" ? [0, 1] : Array.from({ length: Pex }, (_, i) => i);
  add(Pex, "balls at cell centres", { s: ndPairEdge(name) * (1 + 1e-9), pieces: cells.map((cell) => ({ cell, u: new Array(C.n).fill(0) })) });
  // two seeded runs
  for (const P of [4, 24]) {
    if (P === Pex) continue;
    const r = searchBoundary({ polytope: name, piece: "ball", P }, { seed: 7, budget: { evals: 3000 } });
    if (!r.config) throw new Error(`no packing for ${name} ${P}`);
    add(P, "seeded search, seed 7, 3000 evals (seeds finished by the kernel)", r.config);
  }
}
void boundaryKernel;
writeFileSync(out, JSON.stringify({ note: "generated by packages/boundary/scripts/gen-nd-packings.ts", packings }));
console.log("wrote", packings.length);
